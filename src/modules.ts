const ref = (
  key: string,
  label: string,
  table: string,
  required = true,
): Field => ({ key, label, type: "select", ref: table, required });
const select = (
  key: string,
  label: string,
  values: string[],
  labels?: string[],
): Field => ({
  key,
  label,
  type: "select",
  options: values.map((value, i) => ({ value, label: labels?.[i] || value })),
  required: true,
});
