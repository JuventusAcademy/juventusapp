export type Field = {
  key: string;
  label: string;
  type?:
    | "text"
    | "email"
    | "date"
    | "datetime-local"
    | "number"
    | "textarea"
    | "checkbox"
    | "select";
  required?: boolean;
  options?: { value: string; label: string }[];
  ref?: string;
  min?: number;
  max?: number;
  step?: string;
  hint?: string;
};
export type Module = {
  id: string;
  title: string;
  singular: string;
  description: string;
  table: string;
  fields: Field[];
  columns: string[];
  read: Role[];
  write: Role[];
  archive?: string;
  search?: string;
};
